-- Migração 0007 — aba Multas: registro demonstrativo de infrações, conferências documentais e histórico próprio.
-- Propósito:
--   * FINE: projeção atual de cada registro (rascunho → registrado → cancelado), com ocorrência, origem (radar ou
--     agente de trânsito, snapshot gravado pelo servidor), veículo autuado (independente do inventário de viaturas)
--     e andamento informado (etapa, pagamento e contestação independentes);
--   * FINE_DOCUMENT_CHECK: constatações documentais imutáveis (resultado, fonte, data de referência, versão do sujeito);
--   * FINE_EVENT: trilha imutável com autoria, origem, motivo, antes/depois e chave de comando idempotente.
-- Dependências: 0001 (AGENCY, REGION, EQUIPMENT, AGENT, APP_USER) e Firebird 5 (índice parcial).
-- Risco de perda de dados: nenhum (somente CREATE; nenhuma tabela existente muda). Recuperação: restaurar backup gbak.
-- Convenções: instantes _AT em UTC; datas _ON locais de Marília; valores em centavos (INTEGER); RENAVAM é texto
--   (preserva zeros à esquerda). CHECKs condicionais usam COALESCE/IS NULL: um CHECK aceita resultado UNKNOWN.

CREATE TABLE FINE (
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    RECORD_STATE            VARCHAR(12) NOT NULL,
    DESCRIPTION             VARCHAR(240) NOT NULL,
    OCCURRED_AT             TIMESTAMP,
    INFRACTION_KIND         VARCHAR(20),
    LEGAL_REFERENCE         VARCHAR(120),
    INFRACTION_CODE         VARCHAR(20),
    INFRACTION_DETAIL       VARCHAR(10),
    AGENCY_ID               INTEGER,
    EXTERNAL_AIT            VARCHAR(40),
    AIT_KEY                 VARCHAR(40),
    AIT_MISSING_REASON      VARCHAR(160),
    STREET                  VARCHAR(120),
    ADDRESS_REF             VARCHAR(160),
    REGION_ID               INTEGER,
    LAT                     DECIMAL(9,6),
    LNG                     DECIMAL(9,6),
    NOTES                   VARCHAR(1000),
    SOURCE_KIND             VARCHAR(10),
    EQUIPMENT_ID            INTEGER,
    AGENT_ID                INTEGER,
    SOURCE_NOTE             VARCHAR(300),
    SOURCE_SNAPSHOT         BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    SPEED_LIMIT_KMH         SMALLINT,
    SPEED_MEASURED_KMH      SMALLINT,
    SPEED_CONSIDERED_KMH    SMALLINT,
    RADAR_DETAILS           BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    EVIDENCE_REFERENCE      VARCHAR(240),
    VEHICLE_PLATE           VARCHAR(7),
    VEHICLE_UF              CHAR(2),
    VEHICLE_MANUFACTURER    VARCHAR(80),
    VEHICLE_MODEL           VARCHAR(80),
    VEHICLE_SPECIES         VARCHAR(40),
    VEHICLE_COLOR           VARCHAR(30),
    VEHICLE_YEAR            SMALLINT,
    VEHICLE_RENAVAM         VARCHAR(11),
    RENAVAM_MISSING_REASON  VARCHAR(160),
    PROCESS_STAGE           VARCHAR(24) DEFAULT 'NAO_INFORMADA' NOT NULL,
    PAYMENT_STATUS          VARCHAR(24) DEFAULT 'NAO_INFORMADO' NOT NULL,
    CONTEST_STATUS          VARCHAR(16) DEFAULT 'NAO_INFORMADA' NOT NULL,
    CONTEST_KIND            VARCHAR(16),
    NOMINAL_AMOUNT_CENTS    INTEGER,
    AUTUATION_ISSUED_ON     DATE,
    AUTUATION_RECEIVED_ON   DATE,
    PENALTY_ISSUED_ON       DATE,
    PENALTY_RECEIVED_ON     DATE,
    PAYMENT_DUE_ON          DATE,
    DEFENSE_DUE_ON          DATE,
    APPEAL_DUE_ON           DATE,
    PAID_ON                 DATE,
    PAID_AMOUNT_CENTS       INTEGER,
    PAYMENT_REFERENCE       VARCHAR(240),
    CONTEST_SUBMITTED_ON    DATE,
    CONTEST_REFERENCE       VARCHAR(240),
    CONTEST_DECIDED_ON      DATE,
    CONTEST_RESULT_NOTE     VARCHAR(500),
    CLOSED_ON               DATE,
    CLOSURE_REFERENCE       VARCHAR(240),
    CLOSURE_NOTE            VARCHAR(500),
    -- Projeção da conferência na data da ocorrência (última compatível com SUBJECT_VERSION) e contagem dos motivos
    -- "A conferir" que não dependem da data de hoje; ambas recalculadas pelo servidor na mesma transação da mudança.
    OCC_DOC_STATUS          VARCHAR(24) DEFAULT 'NAO_VERIFICADA' NOT NULL,
    OCC_DOC_REVIEW_ON       DATE,
    ATTENTION_COUNT         SMALLINT DEFAULT 0 NOT NULL,
    VERSION_NO              INTEGER DEFAULT 1 NOT NULL,
    SUBJECT_VERSION         INTEGER DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP NOT NULL,
    CREATED_BY              INTEGER,
    UPDATED_BY              INTEGER,
    CREATED_SOURCE          VARCHAR(10) NOT NULL,
    REGISTERED_AT           TIMESTAMP,
    CANCELLED_AT            TIMESTAMP,
    CANCELLED_BY            INTEGER,
    CANCEL_SOURCE           VARCHAR(10),
    CANCEL_REASON           VARCHAR(300),
    CONSTRAINT PK_FINE PRIMARY KEY (ID),
    CONSTRAINT FK_FINE_AGENCY FOREIGN KEY (AGENCY_ID) REFERENCES AGENCY (ID),
    CONSTRAINT FK_FINE_REGION FOREIGN KEY (REGION_ID) REFERENCES REGION (ID),
    CONSTRAINT FK_FINE_EQUIPMENT FOREIGN KEY (EQUIPMENT_ID) REFERENCES EQUIPMENT (ID),
    CONSTRAINT FK_FINE_AGENT FOREIGN KEY (AGENT_ID) REFERENCES AGENT (ID),
    CONSTRAINT FK_FINE_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT FK_FINE_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT FK_FINE_CANCELLED_BY FOREIGN KEY (CANCELLED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT CK_FINE_STATE CHECK (RECORD_STATE IN ('RASCUNHO', 'REGISTRADO', 'CANCELADO')),
    CONSTRAINT CK_FINE_KIND CHECK (INFRACTION_KIND IS NULL OR INFRACTION_KIND IN ('VELOCIDADE', 'AVANCO_SEMAFORO', 'PARADA_FAIXA', 'CONVERSAO_PROIBIDA', 'FAIXA_EXCLUSIVA', 'OUTRA')),
    CONSTRAINT CK_FINE_SOURCE_KIND CHECK (SOURCE_KIND IS NULL OR SOURCE_KIND IN ('RADAR', 'AGENTE')),
    -- Sem origem não há recurso; Agente não tem radar; Radar pode ter agente operador associado.
    CONSTRAINT CK_FINE_SOURCE_IDS CHECK ((SOURCE_KIND IS NULL AND EQUIPMENT_ID IS NULL AND AGENT_ID IS NULL) OR (COALESCE(SOURCE_KIND, '') = 'AGENTE' AND EQUIPMENT_ID IS NULL) OR COALESCE(SOURCE_KIND, '') = 'RADAR'),
    CONSTRAINT CK_FINE_COORDS CHECK ((LAT IS NULL AND LNG IS NULL) OR (LAT IS NOT NULL AND LNG IS NOT NULL AND LAT BETWEEN -90 AND 90 AND LNG BETWEEN -180 AND 180)),
    CONSTRAINT CK_FINE_SPEEDS CHECK ((SPEED_LIMIT_KMH IS NULL OR SPEED_LIMIT_KMH BETWEEN 1 AND 350) AND (SPEED_MEASURED_KMH IS NULL OR SPEED_MEASURED_KMH BETWEEN 1 AND 350)
        AND (SPEED_CONSIDERED_KMH IS NULL OR SPEED_CONSIDERED_KMH BETWEEN 0 AND 350) AND (SPEED_CONSIDERED_KMH IS NULL OR SPEED_MEASURED_KMH IS NULL OR SPEED_CONSIDERED_KMH <= SPEED_MEASURED_KMH)),
    CONSTRAINT CK_FINE_PLATE CHECK (VEHICLE_PLATE IS NULL OR VEHICLE_PLATE SIMILAR TO '[A-Z]{3}[0-9][A-Z0-9][0-9]{2}'),
    CONSTRAINT CK_FINE_RENAVAM CHECK (VEHICLE_RENAVAM IS NULL OR VEHICLE_RENAVAM SIMILAR TO '[0-9]{11}'),
    CONSTRAINT CK_FINE_UF CHECK (VEHICLE_UF IS NULL OR VEHICLE_UF IN ('AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO', 'MA', 'MT', 'MS', 'MG', 'PA', 'PB', 'PR', 'PE', 'PI', 'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO')),
    CONSTRAINT CK_FINE_YEAR CHECK (VEHICLE_YEAR IS NULL OR VEHICLE_YEAR BETWEEN 1900 AND 2200),
    CONSTRAINT CK_FINE_STAGE CHECK (PROCESS_STAGE IN ('NAO_INFORMADA', 'AUTUACAO', 'PENALIDADE_NOTIFICADA', 'ENCERRAMENTO_INFORMADO')),
    CONSTRAINT CK_FINE_PAYMENT CHECK (PAYMENT_STATUS IN ('NAO_INFORMADO', 'SEM_COBRANCA_INFORMADA', 'EM_ABERTO', 'PAGAMENTO_INFORMADO')),
    CONSTRAINT CK_FINE_CONTEST CHECK (CONTEST_STATUS IN ('NAO_INFORMADA', 'NAO_APRESENTADA', 'EM_ANALISE', 'DEFERIDA', 'INDEFERIDA')),
    CONSTRAINT CK_FINE_CONTEST_KIND CHECK (CONTEST_KIND IS NULL OR CONTEST_KIND IN ('DEFESA_PREVIA', 'RECURSO_1', 'RECURSO_2')),
    CONSTRAINT CK_FINE_AMOUNTS CHECK ((NOMINAL_AMOUNT_CENTS IS NULL OR NOMINAL_AMOUNT_CENTS BETWEEN 0 AND 100000000) AND (PAID_AMOUNT_CENTS IS NULL OR PAID_AMOUNT_CENTS BETWEEN 1 AND 100000000)),
    CONSTRAINT CK_FINE_PAID CHECK (PAYMENT_STATUS <> 'PAGAMENTO_INFORMADO' OR (PAID_ON IS NOT NULL AND PAID_AMOUNT_CENTS IS NOT NULL AND PAYMENT_REFERENCE IS NOT NULL)),
    CONSTRAINT CK_FINE_CONTESTED CHECK (CONTEST_STATUS NOT IN ('EM_ANALISE', 'DEFERIDA', 'INDEFERIDA') OR (CONTEST_KIND IS NOT NULL AND CONTEST_SUBMITTED_ON IS NOT NULL AND CONTEST_REFERENCE IS NOT NULL)),
    CONSTRAINT CK_FINE_DECIDED CHECK (CONTEST_STATUS NOT IN ('DEFERIDA', 'INDEFERIDA') OR (CONTEST_DECIDED_ON IS NOT NULL AND CONTEST_RESULT_NOTE IS NOT NULL)),
    CONSTRAINT CK_FINE_CLOSED CHECK (PROCESS_STAGE <> 'ENCERRAMENTO_INFORMADO' OR (CLOSED_ON IS NOT NULL AND CLOSURE_REFERENCE IS NOT NULL AND CLOSURE_NOTE IS NOT NULL)),
    CONSTRAINT CK_FINE_DOC CHECK (OCC_DOC_STATUS IN ('NAO_VERIFICADA', 'REGULARIDADE_INFORMADA', 'PENDENCIA_INFORMADA')),
    CONSTRAINT CK_FINE_VERSIONS CHECK (VERSION_NO >= 1 AND SUBJECT_VERSION >= 1 AND ATTENTION_COUNT >= 0),
    CONSTRAINT CK_FINE_CREATED CHECK (CREATED_SOURCE IN ('MANUAL', 'SEMENTE') AND (CREATED_SOURCE = 'SEMENTE' OR CREATED_BY IS NOT NULL)),
    -- Registrado: campos mínimos completos e origem coerente (radar com equipamento; agente com agente).
    CONSTRAINT CK_FINE_REGISTERED CHECK (RECORD_STATE <> 'REGISTRADO' OR (OCCURRED_AT IS NOT NULL AND INFRACTION_KIND IS NOT NULL AND LEGAL_REFERENCE IS NOT NULL
        AND AGENCY_ID IS NOT NULL AND (EXTERNAL_AIT IS NOT NULL OR AIT_MISSING_REASON IS NOT NULL) AND (STREET IS NOT NULL OR ADDRESS_REF IS NOT NULL)
        AND SOURCE_SNAPSHOT IS NOT NULL AND REGISTERED_AT IS NOT NULL AND VEHICLE_PLATE IS NOT NULL AND VEHICLE_UF IS NOT NULL AND VEHICLE_MANUFACTURER IS NOT NULL
        AND VEHICLE_MODEL IS NOT NULL AND VEHICLE_SPECIES IS NOT NULL AND (VEHICLE_RENAVAM IS NOT NULL OR RENAVAM_MISSING_REASON IS NOT NULL)
        AND ((COALESCE(SOURCE_KIND, '') = 'AGENTE' AND AGENT_ID IS NOT NULL) OR (COALESCE(SOURCE_KIND, '') = 'RADAR' AND EQUIPMENT_ID IS NOT NULL)))),
    CONSTRAINT CK_FINE_REGISTERED_SPEED CHECK (RECORD_STATE <> 'REGISTRADO' OR COALESCE(INFRACTION_KIND, '') <> 'VELOCIDADE' OR (COALESCE(SOURCE_KIND, '') = 'RADAR'
        AND SPEED_LIMIT_KMH IS NOT NULL AND SPEED_MEASURED_KMH IS NOT NULL AND SPEED_CONSIDERED_KMH IS NOT NULL AND SPEED_CONSIDERED_KMH > SPEED_LIMIT_KMH)),
    -- Cancelado: motivo, instante e origem; conta obrigatória salvo na carga confiável de demonstração.
    CONSTRAINT CK_FINE_CANCELLED CHECK ((RECORD_STATE = 'CANCELADO' AND CANCELLED_AT IS NOT NULL AND CANCEL_REASON IS NOT NULL AND CANCEL_SOURCE IS NOT NULL
        AND CANCEL_SOURCE IN ('MANUAL', 'SEMENTE') AND (CANCEL_SOURCE = 'SEMENTE' OR CANCELLED_BY IS NOT NULL))
        OR (RECORD_STATE <> 'CANCELADO' AND CANCELLED_AT IS NULL AND CANCELLED_BY IS NULL AND CANCEL_SOURCE IS NULL AND CANCEL_REASON IS NULL))
);

-- Mesmo AIT no mesmo órgão autuador só uma vez (cancelados conservam a chave). AIT ausente ou órgão ainda não
-- informado não colidem: índice parcial, porque o Firebird considera repetida a chave composta com um segmento NULL.
CREATE UNIQUE INDEX UX_FINE_AIT ON FINE (AGENCY_ID, AIT_KEY) WHERE AIT_KEY IS NOT NULL AND AGENCY_ID IS NOT NULL;

CREATE DESCENDING INDEX IX_FINE_OCCURRED ON FINE (OCCURRED_AT, ID);
CREATE INDEX IX_FINE_AGENCY ON FINE (AGENCY_ID, OCCURRED_AT);
CREATE INDEX IX_FINE_EQUIPMENT ON FINE (EQUIPMENT_ID, OCCURRED_AT);
CREATE INDEX IX_FINE_AGENT ON FINE (AGENT_ID, OCCURRED_AT);
CREATE INDEX IX_FINE_PLATE ON FINE (VEHICLE_PLATE);
CREATE INDEX IX_FINE_RENAVAM ON FINE (VEHICLE_RENAVAM);

-- Constatações documentais: só leitura e inserção para a aplicação. SOURCE = como o dado entrou no demonstrador;
-- SOURCE_TYPE = a evidência apresentada. Nenhuma fonte faz consulta externa.
CREATE TABLE FINE_DOCUMENT_CHECK (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    FINE_ID             INTEGER NOT NULL,
    SUBJECT_VERSION     INTEGER NOT NULL,
    SCOPE               VARCHAR(12) NOT NULL,
    EFFECTIVE_ON        DATE NOT NULL,
    CHECKED_AT          TIMESTAMP NOT NULL,
    DOCUMENT_STATUS     VARCHAR(24) NOT NULL,
    SOURCE_TYPE         VARCHAR(30) NOT NULL,
    SOURCE_REFERENCE    VARCHAR(240),
    CRLV_EXERCISE       SMALLINT,
    PENDING_ITEMS       VARCHAR(500),
    REVIEW_ON           DATE,
    REASON              VARCHAR(300),
    SOURCE              VARCHAR(10) NOT NULL,
    ACTOR_USER_ID       INTEGER,
    CREATED_AT          TIMESTAMP NOT NULL,
    CONSTRAINT PK_FINE_DOCUMENT_CHECK PRIMARY KEY (ID),
    CONSTRAINT FK_FINE_CHECK_FINE FOREIGN KEY (FINE_ID) REFERENCES FINE (ID),
    CONSTRAINT FK_FINE_CHECK_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_FINE_CHECK_SCOPE CHECK (SCOPE IN ('OCORRENCIA', 'POSTERIOR')),
    CONSTRAINT CK_FINE_CHECK_STATUS CHECK (DOCUMENT_STATUS IN ('NAO_VERIFICADA', 'REGULARIDADE_INFORMADA', 'PENDENCIA_INFORMADA')),
    CONSTRAINT CK_FINE_CHECK_SOURCE_TYPE CHECK (SOURCE_TYPE IN ('CRLV_APRESENTADO', 'CONSULTA_OFICIAL_INFORMADA', 'RELATO_MANUAL', 'NAO_INFORMADA')),
    -- Conclusão exige fonte e referência; pendência exige descrição; "Não verificada" explícita exige motivo.
    CONSTRAINT CK_FINE_CHECK_EVIDENCE CHECK (DOCUMENT_STATUS = 'NAO_VERIFICADA' OR (SOURCE_TYPE <> 'NAO_INFORMADA' AND SOURCE_REFERENCE IS NOT NULL)),
    CONSTRAINT CK_FINE_CHECK_PENDING CHECK (DOCUMENT_STATUS <> 'PENDENCIA_INFORMADA' OR PENDING_ITEMS IS NOT NULL),
    CONSTRAINT CK_FINE_CHECK_REASON CHECK (DOCUMENT_STATUS <> 'NAO_VERIFICADA' OR REASON IS NOT NULL),
    CONSTRAINT CK_FINE_CHECK_REVIEW CHECK (REVIEW_ON IS NULL OR REVIEW_ON >= EFFECTIVE_ON),
    CONSTRAINT CK_FINE_CHECK_ORIGIN CHECK (SOURCE IN ('MANUAL', 'SEMENTE') AND (SOURCE = 'SEMENTE' OR ACTOR_USER_ID IS NOT NULL)),
    CONSTRAINT CK_FINE_CHECK_VERSION CHECK (SUBJECT_VERSION >= 1)
);

CREATE INDEX IX_FINE_CHECK_FINE ON FINE_DOCUMENT_CHECK (FINE_ID, SUBJECT_VERSION, SCOPE, CHECKED_AT);

-- Histórico de multas: só leitura e inserção para a aplicação. EVENT_UID = chave do comando emitida pelo servidor no
-- formulário; REQUEST_HASH = impressão digital da operação (tipo, alvo, versão, ator e dados normalizados).
CREATE TABLE FINE_EVENT (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FINE_ID         INTEGER NOT NULL,
    EVENT_UID       VARCHAR(80) NOT NULL,
    REQUEST_HASH    CHAR(64) NOT NULL,
    EVENT_TYPE      VARCHAR(24) NOT NULL,
    SOURCE          VARCHAR(10) NOT NULL,
    ACTOR_USER_ID   INTEGER,
    RECORDED_AT     TIMESTAMP NOT NULL,
    SUMMARY         VARCHAR(240) NOT NULL,
    REASON          VARCHAR(300),
    PAYLOAD         BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    CONSTRAINT PK_FINE_EVENT PRIMARY KEY (ID),
    CONSTRAINT UQ_FINE_EVENT_UID UNIQUE (EVENT_UID),
    CONSTRAINT FK_FINE_EVENT_FINE FOREIGN KEY (FINE_ID) REFERENCES FINE (ID),
    CONSTRAINT FK_FINE_EVENT_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_FINE_EVENT_TYPE CHECK (EVENT_TYPE IN ('CRIACAO', 'EDICAO_RASCUNHO', 'REGISTRO', 'RETIFICACAO', 'CONFERENCIA_DOCUMENTAL', 'ANDAMENTO', 'CANCELAMENTO')),
    CONSTRAINT CK_FINE_EVENT_SOURCE CHECK (SOURCE IN ('MANUAL', 'SEMENTE') AND (SOURCE = 'SEMENTE' OR ACTOR_USER_ID IS NOT NULL))
);

CREATE INDEX IX_FINE_EVENT_FINE ON FINE_EVENT (FINE_ID, RECORDED_AT, ID);
