-- Migração 0005 — atualização automática do planejamento por setores (urban:update).
-- Propósito: guardar, a cada download mensal do Infosiga-SP, só as contagens de Marília por quadrado de 2 km e dia
--            dos últimos 12 meses usados na conta (nunca o arquivo bruto, vítimas ou veículos), com a proveniência.
--            A previsão semanal é recalculada a partir daqui e gravada como uma execução comum (URBAN_RUN).
-- Dependências: 0004.
-- Risco de perda de dados: nenhum (somente CREATE). Recuperação: restaurar backup gbak anterior.

CREATE TABLE URBAN_SNAPSHOT (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    SHA256          CHAR(64) NOT NULL,
    SOURCE_URL      VARCHAR(300) NOT NULL,
    DOWNLOADED_AT   TIMESTAMP NOT NULL,
    BYTES           BIGINT NOT NULL,
    DATA_FROM       DATE NOT NULL,
    DATA_THROUGH    DATE NOT NULL,
    ELIGIBLE        INTEGER NOT NULL,
    AUDIT           BLOB SUB_TYPE TEXT NOT NULL,
    CONSTRAINT PK_URBAN_SNAPSHOT PRIMARY KEY (ID),
    CONSTRAINT UQ_URBAN_SNAPSHOT_SHA UNIQUE (SHA256),
    CONSTRAINT CK_URBAN_SNAPSHOT_VALUES CHECK (BYTES > 0 AND ELIGIBLE >= 0 AND DATA_FROM <= DATA_THROUGH)
);

-- Contagem de registros elegíveis por dia e quadrado (só dias/quadrados com registro; ausência = zero).
CREATE TABLE URBAN_DAILY (
    SNAPSHOT_ID INTEGER NOT NULL,
    DAY_DATE    DATE NOT NULL,
    CELL_NO     SMALLINT NOT NULL,
    COUNT_N     SMALLINT NOT NULL,
    CONSTRAINT PK_URBAN_DAILY PRIMARY KEY (SNAPSHOT_ID, DAY_DATE, CELL_NO),
    CONSTRAINT FK_URBAN_DAILY_SNAPSHOT FOREIGN KEY (SNAPSHOT_ID) REFERENCES URBAN_SNAPSHOT (ID),
    CONSTRAINT CK_URBAN_DAILY_VALUES CHECK (CELL_NO BETWEEN 0 AND 63 AND COUNT_N > 0)
);
