-- Migração 0003 — planejamento preventivo semanal por setores (ADR-0016).
-- Propósito:
--   * execuções importadas do treino separado (ml/marilia-setores), com proveniência e evidências; contagens
--     históricas são REAIS e agregadas (Infosiga-SP/Detran-SP, CC BY 4.0); nada aqui é evento de recurso;
--   * missões FICTÍCIAS de reforço, separadas da telemetria do agente, com no máximo uma vigente por agente
--     (índice único parcial) e histórico das transições.
-- Dependências: 0001, 0002 e Firebird 5 (DECFLOAT, índice parcial).
-- Risco de perda de dados: nenhum (somente CREATE). Recuperação: restaurar backup gbak anterior.
-- Estimativas em DECFLOAT(34): o texto mais curto do double do JSON volta idêntico (DOUBLE PRECISION perde o último bit
-- pelo PDO). Datas de previsão são DATE locais de Marília; intervalos [FROM, UNTIL) com fim exclusivo.

CREATE TABLE URBAN_RUN (
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    BUNDLE_SHA256           CHAR(64) NOT NULL,
    PROTOCOL_VERSION        VARCHAR(40) NOT NULL,
    AS_OF                   DATE NOT NULL,
    UNTIL_DATE              DATE NOT NULL,
    DATA_REFERENCE_THROUGH  DATE NOT NULL,
    GENERATED_AT            TIMESTAMP NOT NULL,
    SOURCE_SNAPSHOT_SHA256  CHAR(64) NOT NULL,
    SELECTED_METHOD         VARCHAR(10) NOT NULL,
    CANDIDATE_METHOD        VARCHAR(10) NOT NULL,
    TEST_RELATIVE_GAIN      DECFLOAT(34) NOT NULL,
    MODEL_ISSUED_AT         DATE NOT NULL,
    NOTICE                  VARCHAR(300) NOT NULL,
    EVALUATION              BLOB SUB_TYPE TEXT NOT NULL,
    MODEL                   BLOB SUB_TYPE TEXT NOT NULL,
    PROVENANCE              BLOB SUB_TYPE TEXT NOT NULL,
    FILES                   BLOB SUB_TYPE TEXT NOT NULL,
    IMPORTED_AT             TIMESTAMP NOT NULL,
    CONSTRAINT PK_URBAN_RUN PRIMARY KEY (ID),
    CONSTRAINT UQ_URBAN_RUN_BUNDLE UNIQUE (BUNDLE_SHA256),
    CONSTRAINT CK_URBAN_RUN_METHOD CHECK (SELECTED_METHOD IN ('baseline', 'poisson') AND CANDIDATE_METHOD = 'poisson'),
    CONSTRAINT CK_URBAN_RUN_PERIOD CHECK (UNTIL_DATE = DATEADD(7 DAY TO AS_OF) AND DATA_REFERENCE_THROUGH < AS_OF)
);

-- Setores experimentais da execução (retângulos WGS84; não são bairros nem limite municipal).
CREATE TABLE URBAN_SECTOR (
    RUN_ID      INTEGER NOT NULL,
    SECTOR_ID   CHAR(2) NOT NULL,
    NAME        VARCHAR(80) NOT NULL,
    SOUTH       DECIMAL(9,6) NOT NULL,
    NORTH       DECIMAL(9,6) NOT NULL,
    WEST        DECIMAL(9,6) NOT NULL,
    EAST        DECIMAL(9,6) NOT NULL,
    CENTER_LAT  DECIMAL(9,6) NOT NULL,
    CENTER_LNG  DECIMAL(9,6) NOT NULL,
    CONSTRAINT PK_URBAN_SECTOR PRIMARY KEY (RUN_ID, SECTOR_ID),
    CONSTRAINT FK_URBAN_SECTOR_RUN FOREIGN KEY (RUN_ID) REFERENCES URBAN_RUN (ID),
    CONSTRAINT CK_URBAN_SECTOR_ID CHECK (SECTOR_ID IN ('NO', 'NE', 'SO', 'SE')),
    CONSTRAINT CK_URBAN_SECTOR_BOX CHECK (SOUTH < NORTH AND WEST < EAST AND SOUTH >= -90 AND NORTH <= 90 AND WEST >= -180 AND EAST <= 180)
);

-- Previsão da semana por setor: as duas estimativas e as evidências do corte de informação.
CREATE TABLE URBAN_FORECAST (
    RUN_ID              INTEGER NOT NULL,
    SECTOR_ID           CHAR(2) NOT NULL,
    RANK_NO             SMALLINT NOT NULL,
    PRIORITY            VARCHAR(12) NOT NULL,
    EXPECTED_COUNT      DECFLOAT(34) NOT NULL,
    EXPECTED_ML         DECFLOAT(34) NOT NULL,
    EXPECTED_BASELINE   DECFLOAT(34) NOT NULL,
    HISTORY_START       DATE NOT NULL,
    HISTORY_THROUGH     DATE NOT NULL,
    COUNT_13W           INTEGER NOT NULL,
    COUNT_52W           INTEGER NOT NULL,
    DATA_AGE_DAYS       SMALLINT NOT NULL,
    CONSTRAINT PK_URBAN_FORECAST PRIMARY KEY (RUN_ID, SECTOR_ID),
    CONSTRAINT FK_URBAN_FORECAST_SECTOR FOREIGN KEY (RUN_ID, SECTOR_ID) REFERENCES URBAN_SECTOR (RUN_ID, SECTOR_ID),
    CONSTRAINT UQ_URBAN_FORECAST_RANK UNIQUE (RUN_ID, RANK_NO),
    CONSTRAINT CK_URBAN_FORECAST_RANK CHECK (RANK_NO BETWEEN 1 AND 4 AND PRIORITY = IIF(RANK_NO = 1, 'PRIORITARIA', 'ACOMPANHAR')),
    CONSTRAINT CK_URBAN_FORECAST_VALUES CHECK (EXPECTED_COUNT >= 0 AND EXPECTED_ML >= 0 AND EXPECTED_BASELINE >= 0
        AND COUNT_13W >= 0 AND COUNT_52W >= COUNT_13W AND DATA_AGE_DAYS >= 0 AND HISTORY_START <= HISTORY_THROUGH)
);

-- Retrospecto do teste: previsão do modelo congelado por semana/setor e o que foi registrado depois.
CREATE TABLE URBAN_REPLAY (
    RUN_ID              INTEGER NOT NULL,
    WEEK_FROM           DATE NOT NULL,
    WEEK_UNTIL          DATE NOT NULL,
    SECTOR_ID           CHAR(2) NOT NULL,
    EXPECTED_ML         DECFLOAT(34) NOT NULL,
    EXPECTED_BASELINE   DECFLOAT(34) NOT NULL,
    OBSERVED_COUNT      INTEGER NOT NULL,
    HISTORY_START       DATE NOT NULL,
    HISTORY_THROUGH     DATE NOT NULL,
    COUNT_13W           INTEGER NOT NULL,
    COUNT_52W           INTEGER NOT NULL,
    DATA_AGE_DAYS       SMALLINT NOT NULL,
    CONSTRAINT PK_URBAN_REPLAY PRIMARY KEY (RUN_ID, WEEK_FROM, SECTOR_ID),
    CONSTRAINT FK_URBAN_REPLAY_SECTOR FOREIGN KEY (RUN_ID, SECTOR_ID) REFERENCES URBAN_SECTOR (RUN_ID, SECTOR_ID),
    CONSTRAINT CK_URBAN_REPLAY_VALUES CHECK (WEEK_UNTIL = DATEADD(7 DAY TO WEEK_FROM) AND HISTORY_THROUGH < WEEK_FROM
        AND EXPECTED_ML >= 0 AND EXPECTED_BASELINE >= 0 AND OBSERVED_COUNT >= 0 AND COUNT_13W >= 0 AND COUNT_52W >= COUNT_13W)
);

-- Missão fictícia de reforço. Previsão e método ficam congelados na confirmação; o simulador nunca toca nesta tabela.
CREATE TABLE URBAN_MISSION (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    RUN_ID              INTEGER NOT NULL,
    SECTOR_ID           CHAR(2) NOT NULL,
    PERIOD_FROM         DATE NOT NULL,
    PERIOD_UNTIL        DATE NOT NULL,
    METHOD              VARCHAR(10) NOT NULL,
    EXPECTED_COUNT      DECFLOAT(34) NOT NULL,
    RANK_NO             SMALLINT NOT NULL,
    AGENT_ID            INTEGER NOT NULL,
    SELECTION           VARCHAR(10) NOT NULL,
    REASON              VARCHAR(300) NOT NULL,
    JUSTIFICATION       VARCHAR(300),
    SUPPORT_POINT       VARCHAR(160),
    NOTE                VARCHAR(300),
    STATE               VARCHAR(12) NOT NULL,
    CONFIRMED_AT        TIMESTAMP NOT NULL,
    CONFIRMED_BY        INTEGER NOT NULL,
    CLOSED_AT           TIMESTAMP,
    CLOSED_BY           INTEGER,
    CLOSE_REASON        VARCHAR(300),
    CONSTRAINT PK_URBAN_MISSION PRIMARY KEY (ID),
    CONSTRAINT FK_URBAN_MISSION_SECTOR FOREIGN KEY (RUN_ID, SECTOR_ID) REFERENCES URBAN_SECTOR (RUN_ID, SECTOR_ID),
    CONSTRAINT FK_URBAN_MISSION_AGENT FOREIGN KEY (AGENT_ID) REFERENCES AGENT (ID),
    CONSTRAINT FK_URBAN_MISSION_CONFIRMED_BY FOREIGN KEY (CONFIRMED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT FK_URBAN_MISSION_CLOSED_BY FOREIGN KEY (CLOSED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT CK_URBAN_MISSION_METHOD CHECK (METHOD IN ('baseline', 'poisson') AND EXPECTED_COUNT >= 0 AND RANK_NO BETWEEN 1 AND 4),
    CONSTRAINT CK_URBAN_MISSION_SELECTION CHECK (SELECTION IN ('SUGERIDO', 'MANUAL') AND (SELECTION = 'SUGERIDO' OR JUSTIFICATION IS NOT NULL)),
    CONSTRAINT CK_URBAN_MISSION_STATE CHECK (STATE IN ('CONFIRMADA', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT CK_URBAN_MISSION_CLOSED CHECK ((STATE = 'CONFIRMADA') = (CLOSED_AT IS NULL) AND (STATE = 'CONFIRMADA' OR CLOSE_REASON IS NOT NULL)),
    CONSTRAINT CK_URBAN_MISSION_PERIOD CHECK (PERIOD_UNTIL > PERIOD_FROM)
);

-- Reserva atômica: no máximo uma missão vigente por agente, mesmo com confirmações simultâneas.
CREATE UNIQUE INDEX UX_URBAN_MISSION_ACTIVE ON URBAN_MISSION (AGENT_ID) WHERE STATE = 'CONFIRMADA';

-- Histórico das transições (só SELECT/INSERT para a aplicação).
CREATE TABLE URBAN_MISSION_LOG (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    MISSION_ID      INTEGER NOT NULL,
    FROM_STATE      VARCHAR(12),
    TO_STATE        VARCHAR(12) NOT NULL,
    ACTOR_USER_ID   INTEGER NOT NULL,
    AT_TIME         TIMESTAMP NOT NULL,
    NOTE            VARCHAR(300),
    CONSTRAINT PK_URBAN_MISSION_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_URBAN_MISSION_LOG_MISSION FOREIGN KEY (MISSION_ID) REFERENCES URBAN_MISSION (ID),
    CONSTRAINT FK_URBAN_MISSION_LOG_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER (ID)
);

CREATE INDEX IX_URBAN_MISSION_LOG ON URBAN_MISSION_LOG (MISSION_ID, ID);
