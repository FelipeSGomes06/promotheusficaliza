-- Migração 0009 — acompanhamento dos alertas (pedido de 24/10/2026; ADR-0022).
-- Propósito: registrar o que acontece entre a ciência e o encerramento — responsável (uma conta de APP_USER, pelo ID),
-- providências só de acréscimo, próxima conferência — e o motivo de encerramento de cada alerta.
-- Dependências: 0001. Não altera linhas existentes: alertas antigos ficam com RESOLVED_REASON nulo ("motivo não
-- registrado"), sem responsável e sem providências; ACK_BY/ACK_AT/ACK_NOTE continuam sendo a nota da ciência.
-- Risco de perda de dados: nenhum (só acrescenta colunas e uma tabela). Recuperação: restaurar backup gbak anterior.

-- FOLLOWUP_NO é a versão do acompanhamento: cada atribuição ou providência a incrementa; um formulário aberto antes
-- de outra pessoa agir chega com a versão antiga e é recusado sem perder a digitação.
ALTER TABLE ALERT ADD RESOLVED_REASON VARCHAR(24);
ALTER TABLE ALERT ADD ASSIGNEE_ID INTEGER;
ALTER TABLE ALERT ADD NEXT_CHECK_AT TIMESTAMP;
ALTER TABLE ALERT ADD FOLLOWUP_NO INTEGER DEFAULT 0 NOT NULL;

ALTER TABLE ALERT ADD CONSTRAINT FK_ALERT_ASSIGNEE FOREIGN KEY (ASSIGNEE_ID) REFERENCES APP_USER (ID);
ALTER TABLE ALERT ADD CONSTRAINT CK_ALERT_RESOLVED_REASON CHECK (RESOLVED_REASON IS NULL
    OR (STATE = 'RESOLVIDO' AND RESOLVED_REASON IN ('POSICAO_RECEBIDA', 'FORA_DE_TURNO', 'ARQUIVADO', 'CAUSA_ENCERRADA')));

-- Histórico do acompanhamento (append-only para o usuário da aplicação: só SELECT e INSERT).
-- PROVIDENCIA: o que alguém fez por outro meio (o sistema não envia mensagem). ATRIBUICAO: de qual conta para qual.
CREATE TABLE ALERT_FOLLOWUP (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ALERT_ID        INTEGER NOT NULL,
    KIND            VARCHAR(12) NOT NULL,
    ACTION_CODE     VARCHAR(24),
    NOTE            VARCHAR(500),
    ASSIGNEE_FROM   INTEGER,
    ASSIGNEE_TO     INTEGER,
    NEXT_CHECK_AT   TIMESTAMP,
    CREATED_BY      INTEGER NOT NULL,
    CREATED_AT      TIMESTAMP NOT NULL,
    CONSTRAINT PK_ALERT_FOLLOWUP PRIMARY KEY (ID),
    CONSTRAINT FK_FOLLOWUP_ALERT FOREIGN KEY (ALERT_ID) REFERENCES ALERT (ID),
    CONSTRAINT FK_FOLLOWUP_FROM FOREIGN KEY (ASSIGNEE_FROM) REFERENCES APP_USER (ID),
    CONSTRAINT FK_FOLLOWUP_TO FOREIGN KEY (ASSIGNEE_TO) REFERENCES APP_USER (ID),
    CONSTRAINT FK_FOLLOWUP_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT CK_FOLLOWUP_KIND CHECK (
        (KIND = 'PROVIDENCIA' AND ACTION_CODE IN ('CONTATO_TENTADO', 'CONTATO_CONFIRMADO', 'COMUNICACAO_VERIFICADA', 'OUTRA')
            AND ASSIGNEE_FROM IS NULL AND ASSIGNEE_TO IS NULL AND (ACTION_CODE <> 'OUTRA' OR NOTE IS NOT NULL))
        OR (KIND = 'ATRIBUICAO' AND ACTION_CODE IS NULL AND NEXT_CHECK_AT IS NULL AND ASSIGNEE_TO IS NOT NULL
            AND ASSIGNEE_FROM IS DISTINCT FROM ASSIGNEE_TO))
);

CREATE INDEX IX_FOLLOWUP_ALERT ON ALERT_FOLLOWUP (ALERT_ID, ID);
