-- Migração 0001 — esquema inicial do Promotheus Fiscaliza (Firebird 5, dialeto 3, UTF8).
-- Propósito: inventário (órgãos, bairros, equipamentos, agentes), manutenção, eventos, alertas,
--            contas, tentativas de login, análise preventiva e metadados da instalação.
-- Dependências: banco vazio criado com DEFAULT CHARACTER SET UTF8.
-- Risco de perda de dados: nenhum (somente CREATE). Recuperação: restaurar backup gbak anterior.
-- Convenções:
--   * instantes (sufixo _AT) são TIMESTAMP em UTC; datas de manutenção (DUE_DATE) são DATE no fuso de Marília;
--   * coordenadas WGS84 em graus decimais, DECIMAL(9,6), ordem (LAT, LNG);
--   * VERSION_NO implementa bloqueio otimista dos formulários;
--   * ARCHIVED_AT preenchido = fora da operação atual (histórico preservado).
-- Cada instrução termina com ";" no fim da linha (o migrador divide por esse marcador).

CREATE TABLE APP_META (
    NAME        VARCHAR(40) NOT NULL,
    TEXT_VALUE  VARCHAR(200),
    NUM_VALUE   BIGINT,
    UPDATED_AT  TIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_META PRIMARY KEY (NAME)
);

CREATE TABLE AGENCY (
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CODE        VARCHAR(20) NOT NULL,
    NAME        VARCHAR(120) NOT NULL,
    KIND        VARCHAR(20) NOT NULL,
    CONSTRAINT PK_AGENCY PRIMARY KEY (ID),
    CONSTRAINT UQ_AGENCY_CODE UNIQUE (CODE),
    CONSTRAINT CK_AGENCY_KIND CHECK (KIND IN ('TRANSITO', 'GUARDA', 'POLICIA', 'MANUTENCAO', 'TRANSPORTE'))
);

-- Bairro de referência e zona de agrupamento. A zona é um agrupamento de demonstração, não divisão oficial.
CREATE TABLE REGION (
    ID          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NAME        VARCHAR(80) NOT NULL,
    ZONE        VARCHAR(10) NOT NULL,
    CENTER_LAT  DECIMAL(9,6) NOT NULL,
    CENTER_LNG  DECIMAL(9,6) NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (ID),
    CONSTRAINT UQ_REGION_NAME UNIQUE (NAME),
    CONSTRAINT CK_REGION_ZONE CHECK (ZONE IN ('CENTRO', 'NORTE', 'SUL', 'LESTE', 'OESTE'))
);

CREATE TABLE APP_USER (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    USERNAME        VARCHAR(40) NOT NULL,
    DISPLAY_NAME    VARCHAR(80) NOT NULL,
    PASSWORD_HASH   VARCHAR(255) NOT NULL,
    ROLE            VARCHAR(10) NOT NULL,
    ACTIVE          BOOLEAN DEFAULT TRUE NOT NULL,
    LAST_LOGIN_AT   TIMESTAMP,
    CREATED_AT      TIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_USER PRIMARY KEY (ID),
    CONSTRAINT CK_APP_USER_ROLE CHECK (ROLE IN ('OPERADOR', 'ADMIN'))
);

-- Nome de usuário único sem diferenciar maiúsculas/minúsculas.
CREATE UNIQUE INDEX UX_APP_USER_USERNAME ON APP_USER COMPUTED BY (UPPER(USERNAME));

-- Falhas de login para limitar tentativas. KEY_HASH = SHA-256 de "u:<usuário>" ou "ip:<endereço>": não guarda o valor.
CREATE TABLE LOGIN_ATTEMPT (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    KEY_HASH        CHAR(64) NOT NULL,
    ATTEMPTED_AT    TIMESTAMP NOT NULL,
    CONSTRAINT PK_LOGIN_ATTEMPT PRIMARY KEY (ID)
);

CREATE INDEX IX_LOGIN_ATTEMPT_KEY ON LOGIN_ATTEMPT (KEY_HASH, ATTEMPTED_AT);

CREATE TABLE EQUIPMENT (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CODE                VARCHAR(20) NOT NULL,
    ASSET_TAG           VARCHAR(30),
    TYPE_CODE           VARCHAR(20) NOT NULL,
    MANUFACTURER        VARCHAR(80) NOT NULL,
    MODEL               VARCHAR(80) NOT NULL,
    SERIAL_NUMBER       VARCHAR(60),
    AGENCY_ID           INTEGER NOT NULL,
    STATUS              VARCHAR(20) NOT NULL,
    STATUS_CHANGED_AT   TIMESTAMP NOT NULL,
    CEP                 CHAR(9),
    STREET              VARCHAR(120),
    ADDRESS_REF         VARCHAR(160),
    REGION_ID           INTEGER,
    CITY                VARCHAR(60) DEFAULT 'Marília' NOT NULL,
    UF                  CHAR(2) DEFAULT 'SP' NOT NULL,
    LAT                 DECIMAL(9,6),
    LNG                 DECIMAL(9,6),
    LOCATION_KIND       VARCHAR(10) NOT NULL,
    POS_LAT             DECIMAL(9,6),
    POS_LNG             DECIMAL(9,6),
    POS_OBSERVED_AT     TIMESTAMP,
    POS_RECEIVED_AT     TIMESTAMP,
    LAST_SEEN_AT        TIMESTAMP,
    MAINT_INTERVAL_DAYS SMALLINT,
    SPECS               BLOB SUB_TYPE TEXT,
    NOTES               VARCHAR(500),
    INSTALLED_ON        DATE,
    ARCHIVED_AT         TIMESTAMP,
    VERSION_NO          INTEGER DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP NOT NULL,
    CONSTRAINT PK_EQUIPMENT PRIMARY KEY (ID),
    CONSTRAINT UQ_EQUIPMENT_CODE UNIQUE (CODE),
    CONSTRAINT UQ_EQUIPMENT_ASSET_TAG UNIQUE (ASSET_TAG),
    CONSTRAINT FK_EQUIPMENT_AGENCY FOREIGN KEY (AGENCY_ID) REFERENCES AGENCY (ID),
    CONSTRAINT FK_EQUIPMENT_REGION FOREIGN KEY (REGION_ID) REFERENCES REGION (ID),
    CONSTRAINT CK_EQUIPMENT_TYPE CHECK (TYPE_CODE IN ('RADAR', 'CAMERA', 'BALANCA', 'CANCELA', 'TOTEM', 'VEICULO', 'PATINETE')),
    CONSTRAINT CK_EQUIPMENT_STATUS CHECK (STATUS IN ('NAO_INSTALADO', 'OPERACIONAL', 'FALHA', 'MANUTENCAO', 'DESATIVADO', 'FURTADO')),
    CONSTRAINT CK_EQUIPMENT_LOCATION_KIND CHECK (LOCATION_KIND IN ('INSTALADO', 'PLANEJADO', 'BASE')),
    CONSTRAINT CK_EQUIPMENT_CITY CHECK (CITY = 'Marília' AND UF = 'SP'),
    CONSTRAINT CK_EQUIPMENT_CEP CHECK (CEP IS NULL OR CEP SIMILAR TO '[0-9]{5}[-][0-9]{3}'),
    CONSTRAINT CK_EQUIPMENT_COORDS CHECK ((LAT IS NULL AND LNG IS NULL) OR (LAT BETWEEN -90 AND 90 AND LNG BETWEEN -180 AND 180)),
    CONSTRAINT CK_EQUIPMENT_POS CHECK ((POS_LAT IS NULL AND POS_LNG IS NULL) OR (POS_LAT BETWEEN -90 AND 90 AND POS_LNG BETWEEN -180 AND 180 AND POS_OBSERVED_AT IS NOT NULL)),
    CONSTRAINT CK_EQUIPMENT_INTERVAL CHECK (MAINT_INTERVAL_DAYS IS NULL OR MAINT_INTERVAL_DAYS BETWEEN 7 AND 730),
    CONSTRAINT CK_EQUIPMENT_VERSION CHECK (VERSION_NO >= 1)
);

-- Série do fabricante é única por fabricante (não globalmente). Série desconhecida (NULL) não colide.
CREATE UNIQUE INDEX UX_EQUIPMENT_SERIAL ON EQUIPMENT COMPUTED BY (UPPER(TRIM(MANUFACTURER)) || '|' || UPPER(TRIM(SERIAL_NUMBER)));

CREATE INDEX IX_EQUIPMENT_STATUS ON EQUIPMENT (STATUS);

CREATE TABLE AGENT (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    CODE                VARCHAR(20) NOT NULL,
    CALL_SIGN           VARCHAR(40) NOT NULL,
    ROLE                VARCHAR(10) NOT NULL,
    AGENCY_ID           INTEGER NOT NULL,
    STATUS              VARCHAR(20) NOT NULL,
    STATUS_CHANGED_AT   TIMESTAMP NOT NULL,
    BASE_NAME           VARCHAR(80) NOT NULL,
    BASE_STREET         VARCHAR(120),
    BASE_REF            VARCHAR(160),
    BASE_CEP            CHAR(9),
    REGION_ID           INTEGER,
    BASE_LAT            DECIMAL(9,6) NOT NULL,
    BASE_LNG            DECIMAL(9,6) NOT NULL,
    POS_LAT             DECIMAL(9,6),
    POS_LNG             DECIMAL(9,6),
    POS_OBSERVED_AT     TIMESTAMP,
    POS_RECEIVED_AT     TIMESTAMP,
    ARCHIVED_AT         TIMESTAMP,
    VERSION_NO          INTEGER DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP NOT NULL,
    CONSTRAINT PK_AGENT PRIMARY KEY (ID),
    CONSTRAINT UQ_AGENT_CODE UNIQUE (CODE),
    CONSTRAINT FK_AGENT_AGENCY FOREIGN KEY (AGENCY_ID) REFERENCES AGENCY (ID),
    CONSTRAINT FK_AGENT_REGION FOREIGN KEY (REGION_ID) REFERENCES REGION (ID),
    CONSTRAINT CK_AGENT_ROLE CHECK (ROLE IN ('TRANSITO', 'GUARDA', 'POLICIA')),
    CONSTRAINT CK_AGENT_STATUS CHECK (STATUS IN ('EM_ATIVIDADE', 'EM_PAUSA', 'INDISPONIVEL', 'FORA_DE_SERVICO')),
    CONSTRAINT CK_AGENT_CEP CHECK (BASE_CEP IS NULL OR BASE_CEP SIMILAR TO '[0-9]{5}[-][0-9]{3}'),
    CONSTRAINT CK_AGENT_BASE CHECK (BASE_LAT BETWEEN -90 AND 90 AND BASE_LNG BETWEEN -180 AND 180),
    CONSTRAINT CK_AGENT_POS CHECK ((POS_LAT IS NULL AND POS_LNG IS NULL) OR (POS_LAT BETWEEN -90 AND 90 AND POS_LNG BETWEEN -180 AND 180 AND POS_OBSERVED_AT IS NOT NULL)),
    CONSTRAINT CK_AGENT_VERSION CHECK (VERSION_NO >= 1)
);

CREATE TABLE MAINTENANCE_ORDER (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    EQUIPMENT_ID    INTEGER NOT NULL,
    KIND            VARCHAR(12) NOT NULL,
    PRIORITY        VARCHAR(12) NOT NULL,
    STATE           VARCHAR(12) NOT NULL,
    DUE_DATE        DATE,
    REASON          VARCHAR(300) NOT NULL,
    RESOLUTION      VARCHAR(500),
    RESULT_STATUS   VARCHAR(20),
    SOURCE          VARCHAR(10) NOT NULL,
    OPENED_AT       TIMESTAMP NOT NULL,
    STARTED_AT      TIMESTAMP,
    CLOSED_AT       TIMESTAMP,
    OPENED_BY       INTEGER,
    CLOSED_BY       INTEGER,
    VERSION_NO      INTEGER DEFAULT 1 NOT NULL,
    CONSTRAINT PK_MAINTENANCE_ORDER PRIMARY KEY (ID),
    CONSTRAINT FK_MAINT_EQUIPMENT FOREIGN KEY (EQUIPMENT_ID) REFERENCES EQUIPMENT (ID),
    CONSTRAINT FK_MAINT_OPENED_BY FOREIGN KEY (OPENED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT FK_MAINT_CLOSED_BY FOREIGN KEY (CLOSED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT CK_MAINT_KIND CHECK (KIND IN ('CORRETIVA', 'PREVENTIVA')),
    CONSTRAINT CK_MAINT_PRIORITY CHECK (PRIORITY IN ('IMEDIATA', 'PROGRAMADA')),
    CONSTRAINT CK_MAINT_STATE CHECK (STATE IN ('ABERTA', 'EM_EXECUCAO', 'CONCLUIDA', 'CANCELADA')),
    CONSTRAINT CK_MAINT_SOURCE CHECK (SOURCE IN ('MANUAL', 'SIMULADOR', 'SEMENTE', 'SISTEMA')),
    -- Manutenção programada sempre tem data; a imediata pode não ter.
    CONSTRAINT CK_MAINT_DUE CHECK (PRIORITY = 'IMEDIATA' OR DUE_DATE IS NOT NULL),
    CONSTRAINT CK_MAINT_CLOSED CHECK ((STATE IN ('CONCLUIDA', 'CANCELADA')) = (CLOSED_AT IS NOT NULL)),
    CONSTRAINT CK_MAINT_RESULT CHECK (RESULT_STATUS IS NULL OR RESULT_STATUS IN ('OPERACIONAL', 'FALHA', 'DESATIVADO'))
);

CREATE INDEX IX_MAINT_EQUIPMENT ON MAINTENANCE_ORDER (EQUIPMENT_ID, STATE);

-- Histórico de eventos (append-only para o usuário da aplicação: só SELECT e INSERT).
-- OUTCOME: APLICADO mudou o estado atual; HISTORICO ficou só no histórico (atrasado ou sobreposto por estado administrativo).
CREATE TABLE RESOURCE_EVENT (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    EVENT_UID       VARCHAR(64) NOT NULL,
    RESOURCE_KIND   VARCHAR(12) NOT NULL,
    RESOURCE_ID     INTEGER NOT NULL,
    EVENT_TYPE      VARCHAR(30) NOT NULL,
    SOURCE          VARCHAR(10) NOT NULL,
    ACTOR_USER_ID   INTEGER,
    OCCURRED_AT     TIMESTAMP NOT NULL,
    RECEIVED_AT     TIMESTAMP NOT NULL,
    OUTCOME         VARCHAR(10) NOT NULL,
    SUMMARY         VARCHAR(240) NOT NULL,
    PAYLOAD         BLOB SUB_TYPE TEXT,
    CONSTRAINT PK_RESOURCE_EVENT PRIMARY KEY (ID),
    CONSTRAINT UQ_RESOURCE_EVENT_UID UNIQUE (EVENT_UID),
    CONSTRAINT FK_EVENT_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER (ID),
    CONSTRAINT CK_EVENT_KIND CHECK (RESOURCE_KIND IN ('EQUIPAMENTO', 'AGENTE')),
    CONSTRAINT CK_EVENT_SOURCE CHECK (SOURCE IN ('MANUAL', 'SIMULADOR', 'SEMENTE', 'SISTEMA')),
    CONSTRAINT CK_EVENT_OUTCOME CHECK (OUTCOME IN ('APLICADO', 'HISTORICO'))
);

CREATE INDEX IX_EVENT_RESOURCE ON RESOURCE_EVENT (RESOURCE_KIND, RESOURCE_ID, OCCURRED_AT);
CREATE INDEX IX_EVENT_TYPE_OCCURRED ON RESOURCE_EVENT (EVENT_TYPE, OCCURRED_AT);

-- Alertas. OPEN_KEY ("<tipo>:<id>:<motivo>") existe só enquanto o alerta está aberto/reconhecido;
-- o índice único impede dois alertas abertos para a mesma causa, mesmo com escritas concorrentes.
CREATE TABLE ALERT (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    RESOURCE_KIND       VARCHAR(12) NOT NULL,
    RESOURCE_ID         INTEGER NOT NULL,
    REASON              VARCHAR(24) NOT NULL,
    SEVERITY            VARCHAR(8) NOT NULL,
    STATE               VARCHAR(12) NOT NULL,
    OPEN_KEY            VARCHAR(60),
    MESSAGE             VARCHAR(240) NOT NULL,
    OPENED_AT           TIMESTAMP NOT NULL,
    ACK_AT              TIMESTAMP,
    ACK_BY              INTEGER,
    ACK_NOTE            VARCHAR(300),
    RESOLVED_AT         TIMESTAMP,
    CONSTRAINT PK_ALERT PRIMARY KEY (ID),
    CONSTRAINT UQ_ALERT_OPEN_KEY UNIQUE (OPEN_KEY),
    CONSTRAINT FK_ALERT_ACK_BY FOREIGN KEY (ACK_BY) REFERENCES APP_USER (ID),
    CONSTRAINT CK_ALERT_KIND CHECK (RESOURCE_KIND IN ('EQUIPAMENTO', 'AGENTE')),
    CONSTRAINT CK_ALERT_SEVERITY CHECK (SEVERITY IN ('CRITICA', 'ALTA', 'MEDIA')),
    CONSTRAINT CK_ALERT_STATE CHECK (STATE IN ('ABERTO', 'RECONHECIDO', 'RESOLVIDO')),
    CONSTRAINT CK_ALERT_OPEN_KEY CHECK ((STATE = 'RESOLVIDO') = (OPEN_KEY IS NULL))
);

CREATE INDEX IX_ALERT_STATE ON ALERT (STATE, OPENED_AT);

-- Análise preventiva: cada execução é registrada com método, parâmetros e período, para ser reproduzível.
CREATE TABLE ANALYSIS_RUN (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    METHOD_VERSION  VARCHAR(20) NOT NULL,
    AS_OF           TIMESTAMP NOT NULL,
    HORIZON_DAYS    SMALLINT NOT NULL,
    DATA_FROM       TIMESTAMP,
    DATA_TO         TIMESTAMP NOT NULL,
    EVENTS_USED     INTEGER NOT NULL,
    PARAMS          BLOB SUB_TYPE TEXT NOT NULL,
    EVALUATION      BLOB SUB_TYPE TEXT,
    CREATED_AT      TIMESTAMP NOT NULL,
    CREATED_BY      INTEGER,
    CONSTRAINT PK_ANALYSIS_RUN PRIMARY KEY (ID),
    CONSTRAINT FK_ANALYSIS_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (ID),
    CONSTRAINT CK_ANALYSIS_HORIZON CHECK (HORIZON_DAYS BETWEEN 1 AND 90)
);

CREATE TABLE ANALYSIS_RESULT (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    RUN_ID          INTEGER NOT NULL,
    EQUIPMENT_ID    INTEGER NOT NULL,
    ATTENTION       VARCHAR(14) NOT NULL,
    SCORE           SMALLINT,
    FACTORS         BLOB SUB_TYPE TEXT NOT NULL,
    RECOMMENDATION  VARCHAR(300) NOT NULL,
    HISTORY_DAYS    INTEGER NOT NULL,
    CONSTRAINT PK_ANALYSIS_RESULT PRIMARY KEY (ID),
    CONSTRAINT FK_RESULT_RUN FOREIGN KEY (RUN_ID) REFERENCES ANALYSIS_RUN (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RESULT_EQUIPMENT FOREIGN KEY (EQUIPMENT_ID) REFERENCES EQUIPMENT (ID),
    CONSTRAINT UQ_RESULT_RUN_EQUIPMENT UNIQUE (RUN_ID, EQUIPMENT_ID),
    CONSTRAINT CK_RESULT_ATTENTION CHECK (ATTENTION IN ('ALTA', 'MODERADA', 'BAIXA', 'INSUFICIENTE', 'CORRETIVA')),
    CONSTRAINT CK_RESULT_SCORE CHECK (SCORE IS NULL OR SCORE BETWEEN 0 AND 100)
);
