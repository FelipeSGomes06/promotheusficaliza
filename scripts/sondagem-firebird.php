<?php

// Sondagem exploratória do driver real (não é teste automatizado; os testes PHPUnit cobrem o contrato).
declare(strict_types=1);
$dsn = getenv('DB_TEST_DSN');
$u = getenv('DB_MIGRATION_USER');
$p = getenv('DB_MIGRATION_PASSWORD');
$o = [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC];
$a = new PDO($dsn, $u, $p, $o);
$show = fn($l, $v) => print(str_pad($l, 34) . var_export($v, true) . PHP_EOL);
$show('autocommit', $a->getAttribute(PDO::ATTR_AUTOCOMMIT));
$show('server', $a->getAttribute(PDO::ATTR_SERVER_VERSION));
$show('client', $a->getAttribute(PDO::ATTR_CLIENT_VERSION));
$show('case', $a->getAttribute(PDO::ATTR_CASE));
try {
    $a->exec('DROP TABLE PROBE');
} catch (PDOException) {
}
$a->exec("CREATE TABLE PROBE (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(60) NOT NULL, NOTE BLOB SUB_TYPE TEXT, FLAG BOOLEAN, LAT DECIMAL(9,6),
  TS TIMESTAMP, D DATE, BIG BIGINT, N INTEGER, CONSTRAINT UQ_PROBE_NAME UNIQUE (NAME))");
$a->exec("CREATE UNIQUE INDEX UX_PROBE_EXPR ON PROBE COMPUTED BY (UPPER(TRIM(NAME)) || '|' || UPPER(TRIM(CAST(N AS VARCHAR(20)))))");
$s = $a->prepare('INSERT INTO PROBE (NAME, NOTE, FLAG, LAT, TS, D, BIG, N) VALUES (?,?,?,?,?,?,?,?) RETURNING ID');
$s->execute(['Marília — Avenida São João ção', str_repeat('Ç', 5000), true, '-22.213912', '2026-10-18 13:45:01', '2026-10-18', '9007199254740993', null]);
$show('returning', $s->fetch());
$s->execute(['Segundo', null, false, null, null, null, null, 7]);
$show('returning 2', $s->fetchColumn());
$row = $a->query('SELECT * FROM PROBE ORDER BY ID')->fetch();
foreach ($row as $k => $v) {
    $show("  $k (" . gettype($v) . ')', is_string($v) && strlen($v) > 60 ? substr($v, 0, 20) . '…len=' . mb_strlen($v) : $v);
}
$show('bool false row', $a->query('SELECT FLAG, N FROM PROBE WHERE ID=2')->fetch());
$st = $a->prepare('SELECT ID FROM PROBE ORDER BY ID OFFSET ? ROWS FETCH NEXT ? ROWS ONLY');
$st->execute([1, 1]);
$show('paginação OFFSET/FETCH', $st->fetchAll(PDO::FETCH_COLUMN));
$st = $a->prepare('SELECT COUNT(*) FROM PROBE WHERE NAME LIKE ?');
$st->execute(['%João%']);
$show('LIKE acentuado', $st->fetchColumn());
$st = $a->prepare('SELECT COUNT(*) FROM PROBE WHERE UPPER(NAME) CONTAINING UPPER(?)');
$st->execute(['marília']);
$show('CONTAINING case-insens.', $st->fetchColumn());
$show('named param reuse', (function () use ($a) {
    try {
        $q = $a->prepare('SELECT COUNT(*) FROM PROBE WHERE ID = :x OR N = :x');
        $q->execute(['x' => 7]);
        return $q->fetchColumn();
    } catch (Throwable $e) {
        return 'ERRO: ' . $e->getMessage();
    }
})());
// unicidade por expressão com NULL
try {
    $a->exec("INSERT INTO PROBE (NAME, N) VALUES ('segundo ', 7)");
    $show('expr unique dup', 'aceitou (ERRADO)');
} catch (PDOException $e) {
    $show('expr unique dup', 'rejeitado: ' . $e->getCode() . ' ' . substr($e->getMessage(), 0, 120));
}
$a->exec("INSERT INTO PROBE (NAME) VALUES ('nulo1')");
$a->exec("INSERT INTO PROBE (NAME) VALUES ('nulo2')");
$show('múltiplos NULL em expr unique', 'ok');
// rollback
$a->beginTransaction();
$a->exec("INSERT INTO PROBE (NAME) VALUES ('rb1')");
try {
    $a->exec("INSERT INTO PROBE (NAME) VALUES ('rb1')");
} catch (PDOException $e) {
    $a->rollBack();
}
$show('após rollback rb1 existe?', (int) $a->query("SELECT COUNT(*) FROM PROBE WHERE NAME='rb1'")->fetchColumn());
$show('inTransaction após rollback', $a->inTransaction());
// concorrência: duas conexões
$b = new PDO($dsn, $u, $p, $o);
$b->exec('SET STATEMENT TIMEOUT 3 SECOND'); // sem isso a 2ª conexão espera indefinidamente
$a->beginTransaction();
$a->exec("UPDATE PROBE SET N = 100 WHERE ID = 2");
$t0 = microtime(true);
try {
    $b->exec("UPDATE PROBE SET N = 200 WHERE ID = 2");
    $show('B update enquanto A aberto', 'passou?!');
} catch (PDOException $e) {
    $show('B update enquanto A aberto', round(microtime(true) - $t0, 2) . 's ' . $e->getCode() . ' ' . substr($e->getMessage(), 0, 160));
}
$a->commit();
$show('isolation attr', defined('Pdo\Firebird::TRANSACTION_ISOLATION_LEVEL') ? $b->getAttribute(Pdo\Firebird::TRANSACTION_ISOLATION_LEVEL) : 'n/a');
// unique concorrente
$a->beginTransaction();
$a->exec("INSERT INTO PROBE (NAME) VALUES ('corrida')");
$t0 = microtime(true);
try {
    $b->exec("INSERT INTO PROBE (NAME) VALUES ('corrida')");
    $show('B insert duplicado', 'passou?!');
} catch (PDOException $e) {
    $show('B insert duplicado', round(microtime(true) - $t0, 2) . 's ' . $e->getCode() . ' ' . substr($e->getMessage(), 0, 160));
}
$a->rollBack();
$show('constantes Pdo\Firebird', array_keys((new ReflectionClass('Pdo\Firebird'))->getConstants()));
$b = null;
$a->exec('DROP TABLE PROBE');
echo "fim\n";
